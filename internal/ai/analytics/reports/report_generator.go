// GenerateJSON генерирует JSON отчет
func (r *ReportGenerator) GenerateJSON(report *analytics.Report) (string, error) {
	jsonData, err := json.MarshalIndent(report, "", "  ")
	if err != nil {
		return "", err
	}

	return string(jsonData), nil
}
