// ReportGenerator генератор отчетов
type ReportGenerator struct {
	templates map[string]*template.Template
}

// NewReportGenerator создает новый генератор отчетов
func NewReportGenerator() *ReportGenerator {
	return &ReportGenerator{
		templates: make(map[string]*template.Template),
	}
}

// GenerateMarkdown генерирует Markdown отчет
func (r *ReportGenerator) GenerateMarkdown(report *analytics.Report) (string, error) {
	templateStr := `#  CloudBridge Relay AI Analytics Report

**Generated**: {{.Timestamp.Format "2006-01-02 15:04:05"}}
**Report ID**: {{.ID}}

## 📊 Executive Summary
{{.Analysis.Summary}}

## 🔍 Key Insights
{{range .Analysis.Insights}}
- {{.}}
{{end}}

## Critical Issues
{{range .Analysis.CriticalIssues}}
- {{.}}
{{end}}

## Recommendations
{{range .Analysis.Recommendations}}
- {{.}}
{{end}}

##  Performance Assessment
{{.Analysis.Performance}}

## 🏥 System Health
{{if .Metrics.Health}}
- **Overall Status**: {{.Metrics.Health.Overall}}
- **Health Score**: {{.Metrics.Health.Score}}/100
- **Components**:
{{range $component, $status := .Metrics.Health.Components}}
  - {{$component}}: {{$status}}
{{end}}
{{else}}
- Health data not available
{{end}}

## 📊 Metrics Summary
{{if .Metrics.Metrics}}
{{range $source, $data := .Metrics.Metrics}}
### {{$source}} Metrics
{{if eq $source "ai"}}
{{if $aiData := $data}}
{{if $aiMap := $aiData}}
- Anomalies Detected: {{if $aiMap.anomalies_detected}}{{printf "%.0f" $aiMap.anomalies_detected}}{{else}}N/A{{end}}
- Predictions Made: {{if $aiMap.predictions_made}}{{printf "%.0f" $aiMap.predictions_made}}{{else}}N/A{{end}}
- CPU Usage: {{if $aiMap.cpu_usage}}{{printf "%.1f" $aiMap.cpu_usage}}%{{else}}N/A{{end}}
- Memory Usage: {{if $aiMap.memory_usage}}{{printf "%.1f" (div $aiMap.memory_usage 1048576)}} MB{{else}}N/A{{end}}
- Active Alerts: {{if $aiMap.active_alerts}}{{printf "%.0f" $aiMap.active_alerts}}{{else}}N/A{{end}}
- Prediction Accuracy: {{if $aiMap.prediction_accuracy}}{{printf "%.1f" (mul $aiMap.prediction_accuracy 100)}}%{{else}}N/A{{end}}
{{end}}
{{end}}
{{else if eq $source "relay"}}
{{if $relayData := $data}}
{{if $relayMap := $relayData}}
- Active Connections: {{if $relayMap.active_connections}}{{printf "%.0f" $relayMap.active_connections}}{{else}}N/A{{end}}
- Total Connections: {{if $relayMap.connections_total}}{{printf "%.0f" $relayMap.connections_total}}{{else}}N/A{{end}}
- Uptime: {{if $relayMap.uptime_seconds}}{{printf "%.0f" $relayMap.uptime_seconds}} seconds{{else}}N/A{{end}}
- Bytes Transferred: {{if $relayMap.bytes_transferred}}{{printf "%.0f" $relayMap.bytes_transferred}}{{else}}N/A{{end}}
- Error Rate: {{if $relayMap.error_rate}}{{printf "%.2f" (mul $relayMap.error_rate 100)}}%{{else}}N/A{{end}}
- Average Latency: {{if $relayMap.average_latency}}{{printf "%.2f" $relayMap.average_latency}} seconds{{else}}N/A{{end}}
{{end}}
{{end}}
{{else}}
{{printf "%v" $data}}
{{end}}
{{end}}
{{else}}
No metrics data available
{{end}}

## Detected Anomalies
{{if .Metrics.Anomalies}}
{{range .Metrics.Anomalies}}
- **{{.Type}}** ({{.Severity}}): {{.Description}}
  - Value: {{.Value}}
  - Threshold: {{.Threshold}}
  - Time: {{.Timestamp.Format "15:04:05"}}
{{end}}
{{else}}
No anomalies detected
{{end}}

##  Trends
{{if .Metrics.Trends}}
{{range .Metrics.Trends}}
- **{{.Metric}}**: {{.Direction}} ({{printf "%.2f" .Change}}, confidence: {{printf "%.2f" .Confidence}})
{{end}}
{{else}}
No trends detected
{{end}}

---
*Report generated by CloudBridge AI Analytics Engine*
*For more information, visit the AI Analytics API endpoints*
`

	tmpl, err := template.New("report").Funcs(template.FuncMap{
		"div": func(a, b float64) float64 {
			if b == 0 {
				return 0
			}
			return a / b
		},
		"mul": func(a, b float64) float64 {
			return a * b
		},
	}).Parse(templateStr)
	if err != nil {
		return "", err
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, report); err != nil {
		return "", err
	}

	return buf.String(), nil
}

