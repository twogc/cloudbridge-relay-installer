}

log_error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

# Функция отправки сообщения в Telegram
send_telegram_message() {
    local message="$1"
    local parse_mode="${2:-HTML}"
    
    log_info "Отправка сообщения в Telegram..."
    log_info "Сообщение: $message"
    
    # Экранируем только амперсанд для HTML-форматирования
    if [[ "$parse_mode" == "HTML" ]]; then
        message=$(echo "$message" | sed 's/&/\&amp;/g')
    fi
    
    local response=$(curl -s -X POST \
        "https://api.telegram.org/bot${TELEGRAM_BOT_TOKEN}/sendMessage" \
        -d "chat_id=${TELEGRAM_CHAT_ID}" \
        -d "text=${message}" \
        -d "parse_mode=${parse_mode}" \
        -d "disable_web_page_preview=true" \
        2>/dev/null)
    
    if echo "$response" | grep -q '"ok":true'; then
        log_success "Сообщение успешно отправлено в Telegram"
        return 0
    else
        log_error "Ошибка отправки в Telegram: $response"
        return 1
    fi
}

