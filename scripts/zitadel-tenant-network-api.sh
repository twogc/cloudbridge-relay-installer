#!/bin/bash
# Zitadel Tenant Network Management API Examples
# Примеры API вызовов для управления подсетями тенантов

source "$(dirname "$0")/../configs/developer-env.sh"

echo "🌐 Zitadel Tenant Network Management API Examples"
echo ""

# Базовые переменные
TENANT_ID="tenant-216420165"
PEER_ID="peer-test-001"
ALLOCATED_IP="10.100.1.10"

echo "🔧 1. Получение сетевой конфигурации тенанта:"
echo "curl -H \"Authorization: Bearer \$ZITADEL_ADMIN_TOKEN\" \\"
echo "     \"\$ZITADEL_MANAGEMENT_API/tenants/\$TENANT_ID/network-config\""
echo ""

echo "🔧 2. Создание сетевой конфигурации для тенанта:"
echo "curl -X POST \"\$ZITADEL_MANAGEMENT_API/tenants/\$TENANT_ID/network-config\" \\"
echo "     -H \"Authorization: Bearer \$ZITADEL_ADMIN_TOKEN\" \\"
echo "     -H \"Content-Type: application/json\" \\"
echo "     -d '{"
echo "       \"allocated_subnet\": \"10.100.1.0/24\","
echo "       \"ipam_pool\": \"cloudbridge-pool-1\","
echo "       \"network_policies\": [\"allow-intra-tenant\", \"deny-cross-tenant\"],"
echo "       \"allocated_ips\": {}"
echo "     }'"
echo ""

echo "🔧 3. Обновление сетевой конфигурации тенанта:"
echo "curl -X PUT \"\$ZITADEL_MANAGEMENT_API/tenants/\$TENANT_ID/network-config\" \\"
echo "     -H \"Authorization: Bearer \$ZITADEL_ADMIN_TOKEN\" \\"
echo "     -H \"Content-Type: application/json\" \\"
echo "     -d '{"
echo "       \"allocated_subnet\": \"10.100.1.0/24\","
echo "       \"ipam_pool\": \"cloudbridge-pool-1\","
echo "       \"network_policies\": [\"allow-intra-tenant\", \"deny-cross-tenant\"],"
echo "       \"allocated_ips\": {"
echo "         \"\$PEER_ID\": \"\$ALLOCATED_IP\""
echo "       }"
echo "     }'"
echo ""

echo "🔧 4. Получение списка IPAM пулов:"
echo "curl -H \"Authorization: Bearer \$ZITADEL_ADMIN_TOKEN\" \\"
echo "     \"\$ZITADEL_MANAGEMENT_API/ipam/pools\""
echo ""

echo "🔧 5. Выделение подсети из IPAM пула:"
echo "curl -X POST \"\$ZITADEL_MANAGEMENT_API/ipam/pools/cloudbridge-pool-1/allocate-subnet\" \\"
echo "     -H \"Authorization: Bearer \$ZITADEL_ADMIN_TOKEN\" \\"
echo "     -H \"Content-Type: application/json\""
echo ""

echo "🔧 6. Создание IPAM пула:"
echo "curl -X POST \"\$ZITADEL_MANAGEMENT_API/ipam/pools\" \\"
echo "     -H \"Authorization: Bearer \$ZITADEL_ADMIN_TOKEN\" \\"
echo "     -H \"Content-Type: application/json\" \\"
echo "     -d '{"
echo "       \"name\": \"cloudbridge-pool-1\","
echo "       \"cidr\": \"10.0.0.0/8\","
echo "       \"subnet_size\": 24"
echo "     }'"
echo ""

echo "🔧 7. Проверка изоляции тенантов:"
echo "curl -H \"Authorization: Bearer \$ZITADEL_ADMIN_TOKEN\" \\"
echo "     \"\$ZITADEL_MANAGEMENT_API/ipam/validate-isolation\""
echo ""

echo "🔧 8. Получение всех тенантов с сетевыми конфигурациями:"
echo "curl -H \"Authorization: Bearer \$ZITADEL_ADMIN_TOKEN\" \\"
echo "     \"\$ZITADEL_MANAGEMENT_API/tenants?include_network_config=true\""
echo ""

echo "🔧 9. Удаление сетевой конфигурации тенанта:"
echo "curl -X DELETE \"\$ZITADEL_MANAGEMENT_API/tenants/\$TENANT_ID/network-config\" \\"
echo "     -H \"Authorization: Bearer \$ZITADEL_ADMIN_TOKEN\""
echo ""

echo "🔧 10. Синхронизация с CloudBridge Relay:"
echo "curl -X POST \"\$ZITADEL_MANAGEMENT_API/sync/cloudbridge-relay\" \\"
echo "     -H \"Authorization: Bearer \$ZITADEL_ADMIN_TOKEN\" \\"
echo "     -H \"Content-Type: application/json\" \\"
echo "     -d '{"
echo "       \"relay_endpoint\": \"https://relay.2gc.ru\","
echo "       \"sync_tenants\": true,"
echo "       \"sync_network_configs\": true"
echo "     }'"
echo ""

echo "🧪 Примеры выполнения:"
echo ""
echo "# 1. Проверить доступ к Zitadel:"
echo "curl -H \"Authorization: Bearer \$ZITADEL_ADMIN_TOKEN\" \\"
echo "     \"\$ZITADEL_MANAGEMENT_API/orgs/me\""
echo ""

echo "# 2. Создать IPAM пул:"
echo "curl -X POST \"\$ZITADEL_MANAGEMENT_API/ipam/pools\" \\"
echo "     -H \"Authorization: Bearer \$ZITADEL_ADMIN_TOKEN\" \\"
echo "     -H \"Content-Type: application/json\" \\"
echo "     -d '{\"name\": \"cloudbridge-pool-1\", \"cidr\": \"10.0.0.0/8\", \"subnet_size\": 24}'"
echo ""

echo "# 3. Создать сетевую конфигурацию для тестового тенанта:"
echo "curl -X POST \"\$ZITADEL_MANAGEMENT_API/tenants/tenant-test-001/network-config\" \\"
echo "     -H \"Authorization: Bearer \$ZITADEL_ADMIN_TOKEN\" \\"
echo "     -H \"Content-Type: application/json\" \\"
echo "     -d '{\"allocated_subnet\": \"10.100.1.0/24\", \"ipam_pool\": \"cloudbridge-pool-1\", \"network_policies\": [\"allow-intra-tenant\"], \"allocated_ips\": {}}'"
echo ""

echo "📋 Для выполнения примеров:"
echo "  source configs/developer-env.sh"
echo "  bash scripts/zitadel-tenant-network-api.sh"
echo ""

echo "🎯 Цель: Интеграция CloudBridge Relay с Zitadel для управления подсетями тенантов"
